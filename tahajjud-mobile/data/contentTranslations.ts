/** Localized string for a fixed content key, falling back to `fallback` (the English source). */
export function tc(key: string, fallback: string): string {
    const locale = getLocale();
    if (locale === 'en') return fallback;
    return contentTranslations[key]?.[locale as Exclude<Locale, 'en'>] ?? fallback;
}

/** Like `tc`, but substitutes `{placeholder}` tokens from `vars` after localization. */
export function tcVars(key: string, fallback: string, vars: Record<string, string | number>): string {
    let s = tc(key, fallback);
    for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
    return s;
}
